// Generates the <noscript> SEO fallback in index.html from data.js.
// Run: node build-noscript.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const dataSrc = readFileSync('./data.js', 'utf8');
const sandbox = {};
vm.createContext(sandbox);
new vm.Script(
  dataSrc + '\n;globalThis.__out = { PROJECTS, ABOUT, STACK, TIMELINE, IDENTITY };'
).runInContext(sandbox, { timeout: 5000 });
const { PROJECTS, ABOUT, STACK, TIMELINE, IDENTITY } = sandbox.__out;

const esc = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const paras = (body = []) =>
  body
    .filter((b) => b.t === 'p')
    .map((b) => `          <p>${esc(b.v)}</p>`)
    .join('\n');

const projectHtml = PROJECTS.map((p) => {
  const links = [
    p.url ? `<a href="${esc(p.url)}">Source on GitHub</a>` : '',
    p.demo ? `<a href="${esc(p.demo)}">Live demo</a>` : '',
  ]
    .filter(Boolean)
    .join(' &middot; ');
  return `        <article>
          <h3>${esc(p.title)}</h3>
          <p><strong>${esc(p.tags.join(', '))}</strong></p>
          <p>${esc(p.blurb)}</p>
${paras(p.body)}
          <p>${links}</p>
        </article>`;
}).join('\n');

const stackHtml = STACK.map(
  (g) =>
    `          <li><strong>${esc(g.group)}:</strong> ${esc(
      g.items
        .map((i) => {
          const v = String(i.v ?? '').trim();
          return v && v !== '\u2014' && v !== '-' ? `${i.n} ${v}` : i.n;
        })
        .join(', ')
    )}</li>`
).join('\n');

const timelineHtml = TIMELINE.map(
  (t) => `          <li><strong>${esc(t.y)}</strong> &mdash; ${esc(t.v)}</li>`
).join('\n');

const aboutHtml = (ABOUT || [])
  .map((b) => {
    if (b.t === 'p') return `          <p>${esc(b.v)}</p>`;
    if (b.t === 'h') return `          <h3>${esc(String(b.v).replace(/^#+\s*/, ''))}</h3>`;
    if (b.t === 'list' && Array.isArray(b.v))
      return `          <ul>\n${b.v
        .map((i) => `            <li>${esc(typeof i === 'string' ? i : i.v ?? '')}</li>`)
        .join('\n')}\n          </ul>`;
    return '';
  })
  .filter(Boolean)
  .join('\n');

const block = `    <!-- NOSCRIPT:START (generated by build-noscript.mjs — do not edit by hand) -->
    <noscript>
      <style>
        #animeIntro,
        #boot,
        #shell,
        .music-toggle,
        .crt,
        .crt-glow {
          display: none !important;
        }
        html,
        body {
          overflow: auto !important;
          height: auto !important;
        }
      </style>
      <div class="noscript-fallback">
        <header>
          <h1>${esc(IDENTITY.name)}</h1>
          <p>${esc(IDENTITY.role)} &middot; ${esc(IDENTITY.location)}</p>
          <p>${esc(IDENTITY.tagline)}</p>
          <p>
            <a href="mailto:${esc(IDENTITY.email)}">${esc(IDENTITY.email)}</a>
            &middot;
            <a href="${esc(IDENTITY.github)}">github.com/${esc(IDENTITY.handle)}</a>
          </p>
          <p>
            This portfolio is an interactive terminal and needs JavaScript for the full
            experience. The complete content is below.
          </p>
        </header>

        <section>
          <h2>About</h2>
${aboutHtml}
        </section>

        <section>
          <h2>Projects</h2>
${projectHtml}
        </section>

        <section>
          <h2>Stack</h2>
          <ul>
${stackHtml}
          </ul>
        </section>

        <section>
          <h2>Experience</h2>
          <ul>
${timelineHtml}
          </ul>
        </section>
      </div>
    </noscript>
    <!-- NOSCRIPT:END -->`;

let html = readFileSync('./index.html', 'utf8');
const re = /[ \t]*<!-- NOSCRIPT:START[\s\S]*?<!-- NOSCRIPT:END -->/;
if (re.test(html)) {
  html = html.replace(re, block);
} else {
  html = html.replace(/(\n[ \t]*<!-- =+ boot =+ -->)/, `\n${block}\n$1`);
}
writeFileSync('./index.html', html);
console.log('noscript fallback written:', PROJECTS.length, 'projects');
